/// A named logging category selected per call site via the `category:`
/// argument of `#log`.
///
/// Declare categories once as static members, then reference them with
/// leading-dot syntax from any `@Loggable` type — the same pattern as
/// `Notification.Name`:
///
///     extension LogCategory {
///         static let network = LogCategory("network")
///         static let persistence = LogCategory("persistence")
///     }
///
///     @Loggable
///     struct SyncService {
///         func run() {
///             #log(.debug, category: .network, "request issued")
///         }
///     }
///
/// The receiving `logger(for:)` / `_osLog(for:)` accessors are generated by
/// `@Loggable` on every annotated type, backed by a process-wide cache keyed
/// by the subsystem/category pair.
///
/// A category can also put its name in front of every message `#log` sends to
/// it, so the text alone says where a line came from:
///
///     extension LogCategory {
///         static let engineMirroring = LogCategory("EngineMirroring", prefixesMessages: true)
///     }
///
///     #log(.debug, category: .engineMirroring, "requesting engine list")
///     // [EngineMirroring] requesting engine list
public struct LogCategory: Hashable, Sendable {
    /// The category string passed to `os.Logger(subsystem:category:)`.
    public let name: String

    /// Whether `#log(category:)` starts every message logged to this category
    /// with the name in brackets, as in `[Network] request issued`.
    ///
    /// The prefix becomes part of the message text — a `log stream` predicate
    /// on `eventMessage` sees it — while the os_log category stays ``name``.
    /// Only `#log` adds it: a message written through `logger(for:)` by hand
    /// does not get one, and neither does a `#log` without `category:`.
    public let prefixesMessages: Bool

    /// What `#log` puts ahead of a message logged to this category: `"[name] "`,
    /// or the empty string.
    ///
    /// Assembled here rather than at each call: a category is usually a
    /// `static let`, so this is built once instead of once per message.
    let messagePrefix: String

    public init(_ name: String) {
        self.init(name, prefixesMessages: false)
    }

    /// Creates a category, choosing whether `#log(category:)` prefixes the
    /// messages logged to it with `[name] `.
    ///
    /// A separate initializer rather than a defaulted parameter on
    /// ``init(_:)``: with a default, `LogCategory.init` would no longer convert
    /// to a `(String) -> LogCategory`, and `names.map(LogCategory.init)` would
    /// stop compiling.
    public init(_ name: String, prefixesMessages: Bool) {
        self.name = name
        self.prefixesMessages = prefixesMessages
        self.messagePrefix = prefixesMessages ? "[\(name)] " : ""
    }
}

// MARK: - Categories the system gives special meaning

/// The three category strings `os/signpost.h` singles out. They change how the
/// system treats signposts emitted to a log handle carrying them, so they are
/// spelled exactly as the header defines — a typo here does not fail, it just
/// silently produces an ordinary category.
///
/// Only ``pointsOfInterest`` has a Swift counterpart in the SDK
/// (`OSLog.Category.pointsOfInterest`); the other two exist as C macros only.
///
/// These are declared on `LogCategory` rather than a separate signpost-specific
/// type because the system models signposts as riding on the same
/// subsystem/category pairs as logging — see the `@Signpostable` documentation.
/// Passing one to `#log` compiles and simply means "a category by that name",
/// exactly as `OSLog(subsystem:category: .pointsOfInterest)` does.
extension LogCategory {
    /// High-level events used to orient a developer reading performance data.
    /// Instruments displays signposts in this category by default.
    public static let pointsOfInterest = LogCategory("PointsOfInterest")

    /// Signposts disabled by default, reducing runtime overhead. They become
    /// enabled only while a performance tool such as Instruments is recording.
    public static let dynamicTracing = LogCategory("DynamicTracing")

    /// Like ``dynamicTracing``, and additionally captures user backtraces —
    /// more expensive, and likewise only enabled while a tool is recording.
    public static let dynamicStackTracing = LogCategory("DynamicStackTracing")
}

