    @Test func objectProxyChecksTheClassOfEachObject() {
        assertMacro {
            """
            @RuntimeObjectProxy
            protocol IconAppearance {
                var style: UInt8? { get }
                func iconDescription() -> NSObject?
            }
            """
        } expansion: {
            """
            protocol IconAppearance {
                var style: UInt8? { get }
                func iconDescription() -> NSObject?
            }

            /// Signature-checked caller for objects of whatever class they turn out to have, generated by `@RuntimeObjectProxy`.
            nonisolated struct IconAppearanceImplementation: IconAppearance {
                /// Every method this proxy dispatches, with the signature it assumes.
                static let methodRequirements: [ObjCRuntimeToolbox.RuntimeClassProxySupport.MethodRequirement] = [
                    .init(selector: NSSelectorFromString("style"), typeEncoding: "C@:"),
                    .init(selector: NSSelectorFromString("iconDescription"), typeEncoding: "@@:"),
                ]

                /// The object being called into.
                let host: AnyObject

                /// Wraps `host`, or fails when its class does not have every
                /// requirement with the signature this proxy was generated against.
                /// Checked once per class; a mismatch is logged with both encodings.
                init?(_ host: AnyObject) {
                    guard ObjCRuntimeToolbox.RuntimeClassProxySupport.validate(
                        classOf: host,
                        requirements: Self.methodRequirements,
                        proxyTypeName: "IconAppearanceImplementation"
                    ) else {
                        return nil
                    }
                    self.host = host
                }

                nonisolated var style: UInt8? {
                    let selector = NSSelectorFromString("style")
                    guard let implementation = ObjCRuntimeToolbox.RuntimeClassProxySupport.implementation(of: selector, on: host) else {
