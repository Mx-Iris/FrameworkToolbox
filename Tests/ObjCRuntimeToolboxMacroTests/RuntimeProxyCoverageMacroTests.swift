@testable import ObjCRuntimeToolboxMacros

// Initialisers, class methods and block parameters in `@RuntimeClassProxy`, and
// `@RuntimeObjectProxy`. Each used to need `DynamicObject` and a hand-written
// type encoding next to the call; these pin what the macros generate instead.

// MARK: - Expansions

@Suite(.macros([
    "RuntimeClassProxy": RuntimeClassProxyMacro.self,
    "RuntimeObjectProxy": RuntimeObjectProxyMacro.self,
]))
struct RuntimeProxyCoverageExpansionTests {

    @Test func initialisersAllocateAndInitialise() {
        assertMacro {
            """
            @RuntimeClassProxy("ECGridLayer")
            protocol DockGridLayer {
                init?()
                init?(layerSource source: NSObject, rows: Int, columns: Int, scaleFactor: Float, layoutRTL: Bool)
                func layout()
            }
            """
        } expansion: {
            """
            protocol DockGridLayer {
                init?()
                init?(layerSource source: NSObject, rows: Int, columns: Int, scaleFactor: Float, layoutRTL: Bool)
                func layout()
            }

            /// Signature-checked caller for `ECGridLayer`, generated by `@RuntimeClassProxy`.
            nonisolated struct DockGridLayerImplementation: DockGridLayer {
                /// Name of the Objective-C class this proxy calls into.
                static let runtimeClassName: String = "ECGridLayer"

                /// Every method this proxy dispatches, with the signature it assumes.
                static let methodRequirements: [ObjCRuntimeToolbox.RuntimeClassProxySupport.MethodRequirement] = [
                    .init(selector: NSSelectorFromString("init"), typeEncoding: "@@:"),
                    .init(selector: NSSelectorFromString("initWithLayerSource:rows:columns:scaleFactor:layoutRTL:"), typeEncoding: "@@:@qqfB"),
                    .init(selector: NSSelectorFromString("layout"), typeEncoding: "v@:"),
                ]

                /// Whether the class is present and every requirement still matches.
                /// Evaluated once; a mismatch is logged with both encodings.
                static let isSupported: Bool = ObjCRuntimeToolbox.RuntimeClassProxySupport.validate(
                    className: runtimeClassName,
                    requirements: methodRequirements,
                    proxyTypeName: "DockGridLayerImplementation"
                )

                /// The object being called into.
