                /// Wraps `host`, or fails when the class no longer matches what this
                /// proxy was generated against, or when `host` is not one of them.
                init?(_ host: AnyObject) {
                    guard Self.isSupported else {
                        return nil
                    }
                    guard ObjCRuntimeToolbox.RuntimeClassProxySupport.isInstance(host, ofClassNamed: Self.runtimeClassName) else {
                        return nil
                    }
                    self.host = host
                }

                nonisolated init?() {
                    let selector = NSSelectorFromString("init")
                    guard Self.isSupported, let constructed = ObjCRuntimeToolbox.RuntimeClassProxySupport.construct(
                        className: Self.runtimeClassName,
                        initialiser: selector,
                        typeEncoding: "@@:",
                        proxyTypeName: "DockGridLayerImplementation",
