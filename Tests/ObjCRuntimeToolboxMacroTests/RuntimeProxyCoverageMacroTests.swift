// MARK: - Diagnostics

@Suite(.macros([
    "RuntimeClassProxy": RuntimeClassProxyMacro.self,
    "RuntimeObjectProxy": RuntimeObjectProxyMacro.self,
]))
struct RuntimeProxyCoverageDiagnosticsTests {

    @Test func nonFailableInitialiserIsRejected() {
        assertMacro {
            """
            @RuntimeClassProxy("Tile")
            protocol DockTile {
                init(frame: CGRect)
                init!(level: Int)
            }
            """
        } diagnostics: {
            """
            @RuntimeClassProxy("Tile")
            ┬─────────────────────────
            ╰─ ⚠️ @RuntimeClassProxy: the protocol declares nothing to proxy. The generated type will validate an empty requirement list and dispatch nothing.
            protocol DockTile {
                init(frame: CGRect)
                ┬───
                ╰─ 🛑 @RuntimeClassProxy: a proxied initialiser must be failable, 'init?'. Constructing an instance of a class resolved at runtime can fail — the class can be missing, or its initialiser can return nil.
                init!(level: Int)
                    ┬
                    ╰─ 🛑 @RuntimeClassProxy: a proxied initialiser must be failable, 'init?'. Constructing an instance of a class resolved at runtime can fail — the class can be missing, or its initialiser can return nil.
            }
            """
        }
    }

    @Test func initialiserWithAnUnlabelledFirstParameterIsRejected() {
        assertMacro {
            """
            @RuntimeClassProxy("Tile")
            protocol DockTile {
                init?(_ frame: CGRect)
            }
            """
        } diagnostics: {
            """
            @RuntimeClassProxy("Tile")
            ┬─────────────────────────
            ╰─ ⚠️ @RuntimeClassProxy: the protocol declares nothing to proxy. The generated type will validate an empty requirement list and dispatch nothing.
            protocol DockTile {
                init?(_ frame: CGRect)
                      ┬
                      ╰─ 🛑 @RuntimeClassProxy: an initialiser's first parameter needs a label, because the label names the selector — init(frame:) calls initWithFrame:, the way Swift imports Objective-C initialisers.
            }
            """
        }
    }

    @Test func throwingAsyncAndGenericInitialisersAreRejected() {
        assertMacro {
            """
            @RuntimeClassProxy("Tile")
            protocol DockTile {
                init?(frame: CGRect) throws
                init?(level: Int) async
                init?<Source: AnyObject>(source: Source)
            }
            """
        } diagnostics: {
            """
            @RuntimeClassProxy("Tile")
            ┬─────────────────────────
            ╰─ ⚠️ @RuntimeClassProxy: the protocol declares nothing to proxy. The generated type will validate an empty requirement list and dispatch nothing.
            protocol DockTile {
                init?(frame: CGRect) throws
                                     ┬─────
                                     ╰─ 🛑 @RuntimeClassProxy does not support 'throws' initialisers — a failing Objective-C initialiser returns nil, which 'init?' already reports.
                init?(level: Int) async
                                  ┬────
                                  ╰─ 🛑 @RuntimeClassProxy does not support 'async' initialisers — an Objective-C initialiser returns synchronously.
                init?<Source: AnyObject>(source: Source)
                     ┬──────────────────
                     ╰─ 🛑 @RuntimeClassProxy: a proxied initialiser cannot be generic — Objective-C has no generic methods to call.
            }
            """
        }
    }

    @Test func objectProxyRejectsInitialisersAndStaticRequirements() {
        assertMacro {
            """
            @RuntimeObjectProxy
            protocol IconAppearance {
                init?(style: UInt8)
                static func current() -> NSObject?
                static var shared: NSObject? { get }
                var style: UInt8? { get }
            }
            """
        } diagnostics: {
            """
            @RuntimeObjectProxy
            protocol IconAppearance {
                init?(style: UInt8)
                ┬───
                ╰─ 🛑 @RuntimeObjectProxy calls into the objects it is handed and names no class, so it has no class to send a class method or alloc to. Declare this requirement in a @RuntimeClassProxy("ClassName") protocol instead.
                static func current() -> NSObject?
                            ┬──────
                            ╰─ 🛑 @RuntimeObjectProxy calls into the objects it is handed and names no class, so it has no class to send a class method or alloc to. Declare this requirement in a @RuntimeClassProxy("ClassName") protocol instead.
                static var shared: NSObject? { get }
                       ┬──
                       ╰─ 🛑 @RuntimeObjectProxy calls into the objects it is handed and names no class, so it has no class to send a class method or alloc to. Declare this requirement in a @RuntimeClassProxy("ClassName") protocol instead.
                var style: UInt8? { get }
            }
            """
        }
    }

    @Test func objectProxyAppliedToAStructIsRejected() {
        assertMacro {
            """
            @RuntimeObjectProxy
            struct IconAppearance {
            }
            """
        } diagnostics: {
            """
            @RuntimeObjectProxy
            ┬──────────────────
            ╰─ 🛑 @RuntimeObjectProxy can only be applied to a protocol. Protocol requirements have no bodies, which is what lets the declaration stay plain Swift with nothing to stub out.
            struct IconAppearance {
            }
            """
        }
    }

    @Test func nonEscapingBlockParameterIsRejected() {
        assertMacro {
            """
            @RuntimeClassProxy("Uninstaller")
            protocol Uninstaller {
                func uninstallBundleAtURL(_ url: NSURL, handler: @convention(block) (ObjCBool) -> Void)
            }
            """
        } diagnostics: {
            """
            @RuntimeClassProxy("Uninstaller")
            ┬────────────────────────────────
            ╰─ ⚠️ @RuntimeClassProxy: the protocol declares nothing to proxy. The generated type will validate an empty requirement list and dispatch nothing.
            protocol Uninstaller {
                func uninstallBundleAtURL(_ url: NSURL, handler: @convention(block) (ObjCBool) -> Void)
                                                                 ┬────────────────────────────────────
                                                                 ╰─ 🛑 @RuntimeClassProxy: a block parameter must be '@escaping'. Objective-C may keep any block it is handed, and a block made from a non-escaping closure traps the process when the callee keeps it.
            }
            """
        }
    }

    @Test func returnedBlocksAreRejected() {
        assertMacro {
            """
            @RuntimeClassProxy("Uninstaller")
            protocol Uninstaller {
                func completionHandler() -> (@convention(block) () -> Void)?
                var handler: (@convention(block) () -> Void)? { get }
            }
            """
        } diagnostics: {
            """
            @RuntimeClassProxy("Uninstaller")
            ┬────────────────────────────────
            ╰─ ⚠️ @RuntimeClassProxy: the protocol declares nothing to proxy. The generated type will validate an empty requirement list and dispatch nothing.
            protocol Uninstaller {
                func completionHandler() -> (@convention(block) () -> Void)?
                                            ┬───────────────────────────────
                                            ╰─ 🛑 @RuntimeClassProxy return type cannot be a block. Blocks are supported as parameters only.
                var handler: (@convention(block) () -> Void)? { get }
                             ┬───────────────────────────────
                             ╰─ 🛑 @RuntimeClassProxy property cannot be a block. Blocks are supported as parameters only.
            }
            """
        }
    }

    @Test func staticPropertyWithASetterIsRejected() {
        assertMacro {
            """
            @RuntimeClassProxy("Tile")
            protocol DockTile {
                static var shared: NSObject? { get set }
            }
            """
        } diagnostics: {
            """
            @RuntimeClassProxy("Tile")
            ┬─────────────────────────
            ╰─ ⚠️ @RuntimeClassProxy: the protocol declares nothing to proxy. The generated type will validate an empty requirement list and dispatch nothing.
            protocol DockTile {
                static var shared: NSObject? { get set }
                       ┬──
                       ╰─ 🛑 @RuntimeClassProxy: a static property must be read-only, '{ get }'. It reads a class method; setting one is not supported.
            }
            """
        }
    }
}
